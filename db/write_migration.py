#!/usr/bin/env python3
"""Embeds db/convergence2.sql into the legacy convergence migration.

The SQL is executed from the file itself (db/legacy_convergence.sql) at
migration time to keep the migration free of long escaped SQL strings;
the FK drops are extracted into guarded Ruby. Run from the repo root.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "convergence_fixed.sql")
SQL = os.path.join(HERE, "legacy_convergence.sql")
MIG = os.path.join(HERE, "migrate", "20261101000005_legacy_database_convergence.rb")

text = open(SRC, encoding="utf-8").read()
stmts = [s.strip() for s in text.split(";") if s.strip() and not s.strip().startswith("--")]

ddl, fk_drops, fk_adds = [], [], []
for s in stmts:
    m = re.match(r"^ALTER TABLE `([^`]+)` DROP FOREIGN KEY `([^`]+)`$", s)
    a = re.match(r"^ALTER TABLE `([^`]+)` ADD CONSTRAINT `fk_canon_[\w]+`", s)
    if m:
        fk_drops.append((m.group(1), m.group(2)))
    elif a:
        fk_adds.append(s)
    else:
        ddl.append(s)

head = """# frozen_string_literal: true

# Converges a legacy Expertiza database to the reimplementation schema in a
# single step. The 2026 bridge chain (20260320005757 init -> 20261023000000
# finish) already translated most of the legacy tables, but it left the
# legacy DB diverging from the canonical chain in three places:
#
#   * ~26 legacy-only tables still present (goldberg_*, review*, sessions,
#     versions, ...) that no canonical migration creates
#   * column drift: 100+ columns with wrong types / nullability / defaults
#     (int vs bigint, datetime precision, boolean storage, dropped legacy
#     columns that the canonical chain never added)
#   * legacy utf8mb4_general_ci / utf8mb3 / latin1 tables vs the canonical
#     utf8mb4_general_ci
#
# A database built from the clean 2023-2026 chain never had any of the
# legacy tables, so it can never be "patched" into parity the other way;
# this migration instead rewrites the legacy DB to the canonical shape and
# is a no-op on the canonical DB (guarded by legacy_source?).
#
# The DDL lives in db/legacy_convergence.sql (one statement per line-terminated
# semicolon; generated by db/gen_convergence.py from a post-bridge legacy
# schema dump, db/postbridge_schema.sql, against db/schema.rb). It is
# executed with FOREIGN_KEY_CHECKS=0 and is irreversible by design.
class LegacyDatabaseConvergence < ActiveRecord::Migration[8.0]
  DDL_FILE = File.expand_path("../legacy_convergence.sql", __dir__)

  def up
    @was_legacy = legacy_source?
    return unless @was_legacy

    # Drop legacy foreign keys first (each is guarded so a partially
    # completed convergence can be resumed by re-running db:migrate).
    FK_DROPS.each do |table, name|
      exists = select_value(
        "SELECT COUNT(*) FROM information_schema.REFERENTIAL_CONSTRAINTS " \\
        "WHERE CONSTRAINT_SCHEMA = DATABASE() AND CONSTRAINT_NAME = '#{name}' " \\
        "AND TABLE_NAME = '#{table}'"
      )
      execute "ALTER TABLE `#{table}` DROP FOREIGN KEY `#{name}`" if exists.to_i > 0
    end

    connection.execute "SET FOREIGN_KEY_CHECKS = 0"
    begin
      File.read(DDL_FILE).split(";").each do |sql|
        sql = sql.strip
        execute sql unless sql.empty?
      end
    ensure
      connection.execute "SET FOREIGN_KEY_CHECKS = 1"
    end
  end

  def down
    raise ActiveRecord::IrreversibleMigration
  end

  private

  LEGACY_MARKERS = %w[
    sessions goldberg_roles goldberg_users versions
    review_strategies reviews automated_metareviews
    assignments_questionnaires
  ].freeze

  # A legacy Expertiza DB still has tables the canonical chain never creates
  # (goldberg RBAC, sessions, versions, legacy review tables). The clean
  # chain has none of them, so any one present marks a legacy source.
  # After a *partially completed* convergence removed those markers, the
  # absence of a canonical-only table (cakes) marks it instead, so a
  # re-run of db:migrate resumes instead of no-oping a half-converted DB.
  def legacy_source?
    LEGACY_MARKERS.any? { |t| table_exists?(t) } || !table_exists?(:cakes)
  end

  # db:migrate rewrites db/schema.rb from the live database afterwards. On a
  # legacy source the post-convergence dump would reorder/rename things the
  # canonical schema.rb does not (raw SQL does not match schema-load output),
  # so the canonical schema.rb is left untouched and only the canonical chain
  # may dump it.
  def change_schema!
    super unless @was_legacy
  end
"""


def ruby_list(items, indent="    "):
    out = []
    for i in items:
        if isinstance(i, tuple):
            out.append(f"{indent}[{', '.join(repr(x) for x in i)}],")
        else:
            out.append(f"{indent}{repr(i)},")
    return out


body = [head.rstrip(), ""]
body += ["  FK_DROPS = ["]
body += ruby_list(fk_drops)
body += ["  ].freeze", ""]
body += ["  # Canonical foreign keys re-added after the DDL runs.", "  FK_ADDS = ["]
body += ruby_list(fk_adds)
body += ["  ].freeze", "end"]

open(MIG, "w", encoding="utf-8", newline="\n").write("\n".join(body) + "\n")
# The runtime file omits the FK drops (the migration runs those, guarded,
# before reading this file) so a resumed re-run cannot fail on them.
keep = [s for s in stmts
        if not re.match(r"^ALTER TABLE `[^`]+` DROP FOREIGN KEY `[^`]+`$", s)]
file_text = "SET FOREIGN_KEY_CHECKS = 0;\n" + ";\n".join(keep) + ";\nSET FOREIGN_KEY_CHECKS = 1;\n"
open(SQL, "w", encoding="utf-8", newline="\n").write(file_text)
print(f"ddl={len(ddl)} fk_drops={len(fk_drops)} fk_adds={len(fk_adds)} file_stmts={len(keep)}")
sys.stdout.flush()


